"""Hardware debounce filter for mechanical switches and worn buttons.

Suppresses rapid contact chatter / bounce events on key switches and mouse microswitches.
"""

from __future__ import annotations

import time


class DebounceFilter:
    """Filters contact bounce on physical buttons or keys."""

    def __init__(self, debounce_ms: float = 35.0):
        self.debounce_sec = max(0.001, debounce_ms / 1000.0)
        self._last_release: dict[int, float] = {}
        self._last_press: dict[int, float] = {}

    def should_suppress(self, code: int, value: int, now: float | None = None) -> bool:
        """Returns True if the event is spurious contact chatter and should be dropped.

        value: 1 for press, 0 for release, 2 for autorepeat.
        """
        if value == 2:
            return False  # Autorepeat is generated by the OS/driver, not hardware bounce

        t = time.monotonic() if now is None else now

        if value == 1:
            # Press event: check if released within debounce threshold (switch bounce)
            last_rel = self._last_release.get(code, 0.0)
            if (t - last_rel) < self.debounce_sec:
                return True
            self._last_press[code] = t
            return False

        if value == 0:
            # Release event: check if pressed within debounce threshold
            last_pr = self._last_press.get(code, 0.0)
            if (t - last_pr) < self.debounce_sec:
                return True
            self._last_release[code] = t
            return False

        return False
